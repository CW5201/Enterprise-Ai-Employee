def main() -> int:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as fh:
        for t in TASKS:
            fh.write(json.dumps(t, ensure_ascii=False) + "\n")
    print(f"wrote {len(TASKS)} tasks to {OUT}")
    from collections import Counter
    print("by difficulty:", dict(Counter(t["difficulty"] for t in TASKS)))
    print("by task_type:", dict(Counter(t["task_type"] for t in TASKS)))
    flagged = [t["id"] for t in TASKS if "verify" in t.get("notes", "").lower() or "needs_verification" in t.get("notes", "")]
    print(f"tasks still needing GT verification: {flagged}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
