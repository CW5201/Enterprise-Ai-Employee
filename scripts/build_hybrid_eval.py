def write_jsonl(path: Path) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as fh:
        for q in _QUERIES:
            fh.write(
                json.dumps(
                    {
                        "id": q["id"],
                        "query": q["query"],
                        "type": q["type"],
                        "expected_chunk_ids": q["expected_chunk_ids"],
                        "source": q["source"],
                        "title": q["title"],
                        "category": q["category"],
                    },
                    ensure_ascii=False,
                )
                + "\n"
            )
    return len(_QUERIES)


def main() -> int:
    out = PROJECT_ROOT / "data" / "eval" / "hybrid_eval.jsonl"
    n = write_jsonl(out)
    print(f"[build-eval] wrote {n} queries to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
