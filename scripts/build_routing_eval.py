def main() -> int:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as fh:
        for task in TASKS:
            fh.write(json.dumps(task, ensure_ascii=False) + "\n")
    from collections import Counter
    print(f"wrote {len(TASKS)} routing tasks to {OUT}")
    print("by route:", dict(Counter(t["expected_route"] for t in TASKS)))
    print("by task_type:", dict(Counter(t["task_type"] for t in TASKS)))
    print("by difficulty:", dict(Counter(t["difficulty"] for t in TASKS)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
